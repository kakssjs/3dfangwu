export function t(key, vars = {}) {
  const entry = D[key];
  const text = entry ? entry[current === 'en' ? 1 : 0] : key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] === undefined ? `{${name}}` : String(vars[name])));
}

