import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { after, before, test } from 'node:test';
import { count } from 'drizzle-orm';
import { startApi, type Api } from './helpers.ts';
import { referenceEntries, users, contractorProfiles } from '../../src/api/db/schema.ts';
import { referenceSnapshotSchema } from '../../src/api/reference-data/reference-data.ts';
import { studioDir } from '../../src/api/config.ts';
import path from 'node:path';
let api: Api;
const snapshot = referenceSnapshotSchema.parse(JSON.parse(readFileSync(path.join(studioDir, 'data/open-reference/snapshot.json'), 'utf8')));
before(async () => { api = await startApi(); });
after(async () => { await api.close(); });
test('the reviewed real-source snapshot has all categories and detects altered data or duplicate IDs', () => {
  assert.deepEqual([...new Set(snapshot.entries.map(e => e.kind))].sort(), ['building','business','floorplan','material','region']);
  assert.ok(snapshot.entries.length > 3000);
  const first = snapshot.entries[0]!;
  assert.equal(referenceSnapshotSchema.safeParse({...snapshot, entries: [first, first]}).success, false);
  assert.equal(referenceSnapshotSchema.safeParse({...snapshot, entries: [{...first, data: {...first.data, invented: true}}]}).success, false);
  assert.equal(referenceSnapshotSchema.safeParse({...snapshot, entries: [{...first, sourceUrl: 'javascript:alert(1)'}]}).success, false);
});
test('public reference queries preserve attribution, pagination and the unverified distinction', async () => {
  const first = snapshot.entries.find(e => e.kind === 'business')!;
  const row = {...first, retrievedAt: new Date(first.retrievedAt)};
  await api.db.insert(referenceEntries).values(row).onConflictDoNothing();
  await api.db.insert(referenceEntries).values(row).onConflictDoNothing();
  const response = await api.call('GET', '/reference-data?kind=business&limit=1');
  assert.equal(response.status, 200);
  assert.equal(response.body.referenceOnly, true);
  assert.equal(response.body.total, 1);
  assert.equal(response.body.items[0].license, 'ODbL-1.0');
  assert.match(response.body.items[0].attribution, /OpenStreetMap/);
  assert.equal(response.body.items[0].data.verification, 'not_verified');
  const detail = await api.call('GET', '/reference-data/' + encodeURIComponent(first.id));
  assert.equal(detail.status, 200);
  assert.equal(detail.body.item.id, first.id);
  assert.equal((await api.call('GET', '/reference-data?kind=business&offset=1')).body.items.length, 0);
  assert.equal((await api.call('GET', '/reference-data/stats')).body.counts[0].count, 1);
  assert.equal((await api.call('GET', '/reference-data?kind=unknown')).status, 400);
  assert.equal((await api.call('GET', '/reference-data?limit=1000')).status, 400);
  assert.equal((await api.call('GET', '/reference-data?offset=-1')).status, 400);
  assert.equal((await api.call('GET', '/reference-data/missing')).status, 404);
  assert.equal((await api.db.select({n: count()}).from(users))[0]?.n, 0);
  assert.equal((await api.db.select({n: count()}).from(contractorProfiles))[0]?.n, 0);
});
